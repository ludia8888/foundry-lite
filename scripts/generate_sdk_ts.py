def _display_path(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


@dataclass(frozen=True)
class PropertyDef:
    api_name: str
    ts_type: str
    is_required: bool
    is_sensitive: bool


@dataclass(frozen=True)
class ObjectDef:
    api_name: str
    properties: tuple[PropertyDef, ...]


@dataclass(frozen=True)
class ParameterDef:
    api_name: str
    ts_type: str
    is_required: bool


@dataclass(frozen=True)
class ActionDef:
    api_name: str
    target: str
    parameters: tuple[ParameterDef, ...]


@dataclass(frozen=True)
class OntologyDef:
    objects: tuple[ObjectDef, ...]
    actions: tuple[ActionDef, ...]


@dataclass(frozen=True)
class ObjectClientSurface:
    api_name: str
    response_type: str
    methods: tuple[str, ...]


@dataclass(frozen=True)
class ActionClientSurface:
    api_name: str
    target: str
    payload_type: str
    methods: tuple[str, ...]


@dataclass(frozen=True)
class OperationClientSurface:
    api_name: str
    methods: tuple[str, ...]


@dataclass(frozen=True)
class SdkClientSurface:
    system: tuple[str, ...]
    datasets: tuple[str, ...]
    ontology: tuple[str, ...]
    insights: tuple[OperationClientSurface, ...]
    objects: tuple[ObjectClientSurface, ...]
    actions: tuple[ActionClientSurface, ...]
    object_sets: tuple[str, ...]
    materializations: tuple[str, ...]
    operations: tuple[OperationClientSurface, ...]
    helpers: tuple[str, ...]


def load_ontology(path: Path) -> OntologyDef:
    document = _mapping(yaml.safe_load(path.read_text(encoding="utf-8")), "ontology")
    return OntologyDef(
        objects=tuple(_object_def(row) for row in _sequence(document.get("objectTypes"), "objectTypes")),
        actions=tuple(_action_def(row) for row in _sequence(document.get("actionTypes"), "actionTypes")),
    )


def client_surface(ontology: OntologyDef) -> SdkClientSurface:
    return SdkClientSurface(
        system=("health",),
        datasets=("list", "versions", "preview", "inspect"),
        ontology=("catalog", "validate"),
        insights=(OperationClientSurface("reviews", ("list", "create", "get", "assign", "decide")),),
        objects=tuple(ObjectClientSurface(item.api_name, item.api_name, ("get", "query")) for item in ontology.objects),
        actions=tuple(
            ActionClientSurface(item.api_name, item.target, f"{item.api_name}ApplyRequest", ("apply",))
            for item in ontology.actions
        ),
        object_sets=("list", "create", "get"),
        materializations=("run",),
        operations=(
            OperationClientSurface(
                "backupRestore",
                ("preflight", "startRestoreMode", "restoreModeStatus", "approveResume"),
            ),
            OperationClientSurface("deadLetterRecords", ("list", "get", "retry", "bulkRetry", "discard")),
            OperationClientSurface("deadLetterEvents", ("retry",)),
            OperationClientSurface("icebergMaintenance", ("planReadOnly", "plan")),
            OperationClientSurface("index", ("replayObjectType", "replayFailedRun")),
            OperationClientSurface("lineage", ("get",)),
            OperationClientSurface("observability", ("detect",)),
            OperationClientSurface("reconciliation", ("resolve",)),
            OperationClientSurface("runs", ("list", "detail")),
            OperationClientSurface("transforms", ("retry",)),
            OperationClientSurface("workflows", ("startConnectorSync", "get")),
        ),
        helpers=(
            "actionLockKey",
            "classifyFoundryLiteError",
            "collectCursorPages",
            "createInFlightActionLock",
            "createFoundryLiteClient",
            "createRequestId",
            "expectedObjectVersion",
            "idempotencyKey",
            "isRetryableFoundryLiteError",
            "normalizeFoundryLiteError",
            "requestContextHeaders",
            "retryWithBackoff",
        ),
    )


def render_client_surface_json(surface: SdkClientSurface) -> str:
    payload: dict[str, object] = {
        "actions": {item.api_name: list(item.methods) for item in surface.actions},
        "datasets": list(surface.datasets),
        "helpers": list(surface.helpers),
        "insights": {item.api_name: list(item.methods) for item in surface.insights},
        "materializations": list(surface.materializations),
        "objectSets": list(surface.object_sets),
        "objects": {
            "generic": ["get", "query", "links"],
            **{item.api_name: list(item.methods) for item in surface.objects},
        },
        "ontology": list(surface.ontology),
        "operations": {item.api_name: list(item.methods) for item in surface.operations},
        "system": list(surface.system),
    }
    return json.dumps(payload, sort_keys=True, separators=(",", ":"))


