def _display_path(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


@dataclass(frozen=True)
class PropertyDef:
    api_name: str
    ts_type: str
    is_required: bool
    is_sensitive: bool


@dataclass(frozen=True)
class ObjectDef:
    api_name: str
    properties: tuple[PropertyDef, ...]


@dataclass(frozen=True)
class ParameterDef:
    api_name: str
    ts_type: str
    is_required: bool


@dataclass(frozen=True)
class ActionDef:
    api_name: str
    target: str
    parameters: tuple[ParameterDef, ...]


@dataclass(frozen=True)
class OntologyDef:
    objects: tuple[ObjectDef, ...]
    actions: tuple[ActionDef, ...]


@dataclass(frozen=True)
class ObjectClientSurface:
    api_name: str
    response_type: str
    methods: tuple[str, ...]


@dataclass(frozen=True)
class ActionClientSurface:
    api_name: str
    target: str
    payload_type: str
    methods: tuple[str, ...]


@dataclass(frozen=True)
class OperationClientSurface:
    api_name: str
    methods: tuple[str, ...]


@dataclass(frozen=True)
class SdkClientSurface:
    system: tuple[str, ...]
    datasets: tuple[str, ...]
    sources: tuple[OperationClientSurface, ...]
    connectors: tuple[OperationClientSurface, ...]
    ontology: tuple[str, ...]
    insights: tuple[OperationClientSurface, ...]
    media: tuple[OperationClientSurface, ...]
    objects: tuple[ObjectClientSurface, ...]
    actions: tuple[ActionClientSurface, ...]
    object_sets: tuple[str, ...]
    materializations: tuple[str, ...]
    aip: tuple[OperationClientSurface, ...]
    transforms: tuple[str, ...]
    operations: tuple[OperationClientSurface, ...]
    helpers: tuple[str, ...]


def load_ontology(path: Path) -> OntologyDef:
    document = _mapping(yaml.safe_load(path.read_text(encoding="utf-8")), "ontology")
    return OntologyDef(
        objects=tuple(_object_def(row) for row in _sequence(document.get("objectTypes"), "objectTypes")),
        actions=tuple(_action_def(row) for row in _sequence(document.get("actionTypes"), "actionTypes")),
    )


