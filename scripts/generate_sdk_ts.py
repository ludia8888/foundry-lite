        "function parseFoundryLiteEventFrames<",
        "  TEvent extends FoundryLiteOperationStreamEvent,",
        ">(",
        "  buffer: string,",
        "  parseEvent: StreamFoundryLiteOperationEventsOptions<TEvent>['parseEvent'],",
        "): { events: TEvent[]; remainder: string } {",
        "  const normalized = buffer.replace(/\\r\\n/g, '\\n');",
        "  const frames = normalized.split('\\n\\n');",
        "  const remainder = frames.pop() ?? '';",
        "  const events: TEvent[] = [];",
        "  for (const frame of frames) {",
        "    const event = parseFoundryLiteEventFrame(frame, parseEvent);",
        "    if (event) events.push(event);",
        "  }",
        "  return { events, remainder };",
        "}",
