def contract_fingerprint(ontology: OntologyDef) -> str:
    payload = json.dumps(asdict(ontology), sort_keys=True, separators=(",", ":"))
    return sha256(payload.encode("utf-8")).hexdigest()[:16]


def write_or_check_outputs(
    *,
    ontology_path: Path,
    ts_output: Path,
    web_output: Path,
    should_check: bool,
) -> int:
    ontology = load_ontology(ontology_path)
    outputs = {
        ts_output: render_typescript(ontology),
        web_output: render_web_javascript(ontology),
    }
    if should_check:
        stale = [
            path
            for path, content in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print("SDK generation check failed: generated outputs are stale or ontology apiNames changed.")
            for path in stale:
                print(f"- {_display_path(path)}")
            return 1
        print("SDK generation check passed: generated outputs match the active ontology.")
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {_display_path(path)}")
    return 0


