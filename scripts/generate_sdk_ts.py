def _ts_object_client_lines(objects: Sequence[ObjectClientSurface]) -> list[str]:
    lines: list[str] = []
    for object_def in objects:
        path_name = json.dumps(object_def.api_name)
        lines.extend(
            [
                f"      {object_def.api_name}: {{",
                "        get: (id: string, options?: { explain?: boolean }) => {",
                "          const suffix = options?.explain ? '?explain=true' : '';",
                (
                    f"          return request<{object_def.response_type}>(`/api/objects/{object_def.api_name}/"
                    "${encodeURIComponent(id)}${suffix}`);"
                ),
                "        },",
                "        query: (payload: ObjectQueryRequest = {}) =>",
                (
                    f"          request<ObjectQueryResult<{object_def.response_type}>>"
                    f"(`/api/objects/{object_def.api_name}/query`, {{"
                ),
                '            method: "POST",',
                f"            headers: {{ 'Content-Type': 'application/json', 'X-Foundry-Lite-Object': {path_name} }},",
                "            body: JSON.stringify(payload),",
                "          }),",
                "      },",
            ]
        )
    return lines


