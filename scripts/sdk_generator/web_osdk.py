        "function osdkAggregatePagePayload(objectType, base, plan, pageToken) {",
        "  return osdkQueryPayload(",
        "    objectType,",
        "    { ...base, orderBy: undefined, $orderBy: undefined },",
        "    {",
        "      pageSize: 500,",
        "      pageToken: pageToken ?? undefined,",
        "      orderBy: osdkAggregateOrderBy(objectType, base, plan.groupBy),",
        "    },",
        "  );",
        "}",
