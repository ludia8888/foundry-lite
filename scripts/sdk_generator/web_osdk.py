        "          idempotency,",
        "          `osdk.actions.${actionType.apiName}.applyAction`,",
        "        ),",
        "      }).then((result) => {",
        "        if (result.cacheRefresh && options.onCacheRefresh) options.onCacheRefresh(result.cacheRefresh);",
        "        return result;",
        "      });",
        "    },",
        "  };",
