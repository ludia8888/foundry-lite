        "function osdkQueryPayload(objectType, base, options) {",
        "  const filter = mergeOsdkFilters(",
        "    normalizeOsdkFilterInput(objectType, base.where),",
        "    normalizeOsdkFilterInput(objectType, options.where),",
        "  );",
        "  const requestedOrderBy = options.$orderBy !== undefined ? options.$orderBy : options.orderBy;",
        "  const baseOrderBy = base.$orderBy !== undefined ? base.$orderBy : base.orderBy;",
        "  const orderBy = normalizeOsdkOrderBy(objectType, requestedOrderBy ?? baseOrderBy);",
        "  const pageSize = options.$pageSize !== undefined ? options.$pageSize : options.pageSize;",
        "  const pageToken = options.$pageToken !== undefined ? options.$pageToken : options.pageToken;",
        "  return {",
        "    ...(filter ? { filter } : {}),",
        "    ...(orderBy ? { orderBy } : {}),",
        "    ...(pageSize !== undefined ? { limit: pageSize } : {}),",
        "    ...(pageToken !== undefined ? { cursor: pageToken } : {}),",
        "    ...(options.search !== undefined ? { search: options.search } : {}),",
        "  };",
        "}",
