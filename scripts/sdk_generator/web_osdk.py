        "function decorateOsdkInstance(client, objectType, item) {",
        "  if (!('$link' in item)) {",
        "    const links = {};",
        "    for (const entry of osdkLinkEntries(objectType)) {",
        "      links[entry.alias] = createOsdkLinkSet(client, objectType, item, entry);",
        "    }",
        "    Object.defineProperty(item, '$link', { value: links, enumerable: false });",
        "  }",
        "  if (!('$actions' in item)) {",
        "    const actions = {};",
        "    for (const entry of osdkActionEntries(objectType)) {",
        "      actions[entry.alias] = createOsdkBoundAction(client, entry.actionType, item);",
        "    }",
        "    Object.defineProperty(item, '$actions', { value: actions, enumerable: false });",
        "  }",
        "  return item;",
        "}",
