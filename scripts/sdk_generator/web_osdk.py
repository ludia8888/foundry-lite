        "async function consumeObjectSubscription(stream, callbacks, signal) {",
        "  try {",
        "    for await (const frame of stream) {",
        "      if (signal.aborted) return;",
        "      const event = frame.payload;",
        "      if (event.event === 'snapshot') callbacks.onSuccessfulSubscription?.(event);",
        "      else if (event.event === 'object_changed') callbacks.onChange?.(event);",
        "      else if (event.event === 'out_of_date') callbacks.onOutOfDate?.(event);",
        "      else if (event.event === 'error') callbacks.onError?.(event.error);",
        "    }",
        "  } catch (error) {",
        "    if (!signal.aborted) callbacks.onError?.(error);",
        "  }",
        "}",
        "",
        "function startOsdkObjectSubscription(client, objectType, base, callbacks, options = {}) {",
        "  const controller = new AbortController();",
        "  if (options.signal?.aborted) controller.abort();",
        "  options.signal?.addEventListener('abort', () => controller.abort(), { once: true });",
        "  const stream = client.objects.generic.subscribe(",
        "    objectType.apiName,",
        "    osdkSubscriptionPayload(objectType, base, options),",
        "    { ...options, signal: controller.signal },",
        "  );",
        "  const closed = consumeObjectSubscription(stream, callbacks, controller.signal);",
        "  return { unsubscribe: () => controller.abort(), closed };",
        "}",
