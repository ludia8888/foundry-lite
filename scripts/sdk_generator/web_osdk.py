        "function osdkAggregateGroupKey(group) {",
        "  return JSON.stringify(Object.entries(group));",
        "}",
        "",
        "function osdkAggregateItem(plan, states, item) {",
        "  const properties = item.properties ?? {};",
        "  const group = Object.fromEntries(plan.groupBy.map((property) => [property, properties[property] ?? null]));",
        "  const key = osdkAggregateGroupKey(group);",
        "  const state = states.get(key) ?? { group, count: 0 };",
        "  state.count += 1;",
        "  states.set(key, state);",
        "}",
        "",
        "function osdkAggregateResult(plan, states) {",
        "  if (states.size === 0 && plan.groupBy.length === 0) {",
        "    states.set('[]', { group: {}, count: 0 });",
        "  }",
        "  const buckets = Array.from(states.values());",
        "  if (plan.countOrder !== 'unordered') {",
        "    buckets.sort((left, right) =>",
        "      plan.countOrder === 'asc' ? left.count - right.count : right.count - left.count,",
        "    );",
        "  }",
        "  return {",
        "    excludedItems: 0,",
        "    data: buckets.map((state) => ({",
        "      group: state.group,",
        "      metrics: plan.metricNames.map((name) => ({ name, value: state.count })),",
        "    })),",
        "  };",
        "}",
