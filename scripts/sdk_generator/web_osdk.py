        "async function aggregateOsdkObjectSet(client, objectType, base, request) {",
        "  const plan = normalizeOsdkAggregateInput(objectType, request);",
        "  const states = new Map();",
        "  let pageToken = null;",
        "  for (let pageNumber = 0; pageNumber < 100; pageNumber += 1) {",
        "    const result = await client.objects.generic.query(",
        "      objectType.apiName,",
        "      osdkAggregatePagePayload(objectType, base, plan, pageToken),",
        "    );",
        "    const items = Array.isArray(result.items) ? result.items : [];",
        "    for (const item of items) osdkAggregateItem(plan, states, item);",
        "    pageToken = result.nextCursor ?? null;",
        "    if (!pageToken) return osdkAggregateResult(plan, states);",
        "  }",
        "  throw new FoundryLiteApiError(",
        "    0,",
        '    "CURSOR_LIMIT_EXCEEDED",',
        '    "OSDK aggregate exceeded maxPages",',
        "    { maxPages: 100, objectType: objectType.apiName },",
        "    null,",
        "    false,",
        "  );",
        "}",
