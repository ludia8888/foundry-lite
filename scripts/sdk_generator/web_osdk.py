        "function createOsdkLinkSet(client, sourceObjectType, source, entry) {",
        "  return {",
        "    async fetchPage() {",
        "      const links = await client.objects.generic.links(",
        "        sourceObjectType.apiName,",
        "        source.objectId,",
        "        entry.linkType,",
        "      );",
        "      const activeLinks = links.filter((link) => !link.to.targetMissing);",
        "      const items = await Promise.all(activeLinks.map((link) =>",
        "        client.objects.generic.get(entry.targetObjectType.apiName, link.to.objectId),",
        "      ));",
        "      return osdkPage({",
        "        items: items.map((item) => decorateOsdkInstance(client, entry.targetObjectType, item)),",
        "        nextCursor: null,",
        "      });",
        "    },",
        "    async *asyncIter(options = {}) {",
        "      const maxPages = options.maxPages ?? 1;",
        "      if (maxPages < 1) return;",
        "      const page = await this.fetchPage(options);",
        "      yield* page.data;",
        "    },",
        "  };",
        "}",
