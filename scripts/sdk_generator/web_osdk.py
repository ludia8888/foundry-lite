        "function osdkSubscriptionPayload(objectType, base, options) {",
        "  const query = osdkQueryPayload(objectType, base, { pageSize: options.pageSize });",
        "  return {",
        "    filter: query.filter ?? null,",
        "    orderBy: query.orderBy ?? null,",
        "    properties: options.properties ?? null,",
        "    pageSize: options.pageSize ?? query.limit,",
        "    lastSeenObjectChangeSequence: options.lastSeenObjectChangeSequence ?? null,",
        "    maxEvents: options.maxEvents ?? null,",
        "    pollIntervalSeconds: options.pollIntervalSeconds,",
        "  };",
        "}",
