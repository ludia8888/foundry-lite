        "        expectedObjectVersion: options.expectedObjectVersion ?? source.objectVersion,",
        "        params,",
        "        idempotencyKey: options.idempotencyKey,",
        "      }, { onCacheRefresh: options.onCacheRefresh });",
        "    },",
        "  };",
        "}",
