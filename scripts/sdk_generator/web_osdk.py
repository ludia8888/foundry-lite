        "function createOsdkObjectSet(client, objectType, base = {}) {",
        "  return {",
        "    fetchOne(primaryKey, options) {",
        "      return client.objects.generic",
        "        .get(objectType.apiName, primaryKey, options)",
        "        .then((item) => decorateOsdkInstance(client, objectType, item));",
        "    },",
        "    async fetchPage(options = {}) {",
        "      const result = await client.objects.generic.query(",
        "        objectType.apiName,",
        "        osdkQueryPayload(objectType, base, options),",
        "      );",
        "      return osdkPage({",
        "        items: (Array.isArray(result.items) ? result.items : [])",
        "          .map((item) => decorateOsdkInstance(client, objectType, item)),",
        "        nextCursor: result.nextCursor ?? null,",
        "      });",
        "    },",
        "    async *asyncIter(options = {}) {",
        "      let pageToken = options.$pageToken !== undefined ? options.$pageToken : options.pageToken ?? null;",
        "      const maxPages = options.maxPages ?? 100;",
        "      for (let pageNumber = 0; pageNumber < maxPages; pageNumber += 1) {",
        "        const page = await this.fetchPage({ ...options, pageToken, $pageToken: pageToken });",
        "        yield* page.data;",
        "        pageToken = page.nextPageToken;",
        "        if (!pageToken) return;",
        "      }",
        "      throw new FoundryLiteApiError(",
        "        0,",
        '        "CURSOR_LIMIT_EXCEEDED",',
        '        "OSDK object iteration exceeded maxPages",',
        "        { maxPages },",
        "        null,",
        "        false,",
        "      );",
        "    },",
        "    where(filter) {",
        "      return createOsdkObjectSet(client, objectType, {",
        "        ...base,",
        "        where: mergeOsdkFilters(",
        "          normalizeOsdkFilterInput(objectType, base.where),",
        "          normalizeOsdkFilterInput(objectType, filter),",
        "        ),",
        "      });",
        "    },",
        "    orderBy(orderBy) {",
        "      return createOsdkObjectSet(client, objectType, {",
        "        ...base,",
        "        orderBy: normalizeOsdkOrderBy(objectType, orderBy),",
        "      });",
        "    },",
        "    aggregate(request) {",
        "      return aggregateOsdkObjectSet(client, objectType, base, request);",
        "    },",
        "    links(primaryKey, linkType) {",
        "      return client.objects.generic.links(objectType.apiName, primaryKey, linkType);",
        "    },",
        "    subscribe(callbacks, options = {}) {",
        "      return startOsdkObjectSubscription(client, objectType, base, callbacks, options);",
        "    },",
        "  };",
        "}",
