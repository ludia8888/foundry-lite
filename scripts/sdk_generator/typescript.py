def _object_type_lines(object_def: ObjectDef) -> list[str]:
    properties_name = f"{object_def.api_name}Properties"
    lines = [f"export type {properties_name} = {{"]
    for prop in object_def.properties:
        suffix = "" if prop.is_required else "?"
        lines.append(f"  {prop.api_name}{suffix}: {prop.ts_type};")
    lines += [
        "};",
        f'export type {object_def.api_name} = FoundryLiteObject<"{object_def.api_name}", {properties_name}>;',
        "",
    ]
    return lines


def _action_type_lines(action_def: ActionDef) -> list[str]:
    params_name = f"{action_def.api_name}Params"
    validation_payload_name = f"{action_def.api_name}ValidateRequest"
    payload_name = f"{action_def.api_name}ApplyRequest"
    batch_payload_name = f"{action_def.api_name}ApplyBatchRequest"
    lines = _action_struct_type_lines(action_def)
    lines.append(f"export type {params_name} = {{")
    for param in action_def.parameters:
        suffix = "" if param.is_required else "?"
        lines.append(f"  {param.api_name}{suffix}: {param.ts_type};")
    lines += [
        "};",
        f"export type {validation_payload_name} = {{",
        *(["  objectType: string;"] if action_def.target_kind == "interface" else []),
        "  objectId: string;",
        "  expectedObjectVersion: number;",
        f"  params: {params_name};",
        "};",
        f"export type {payload_name} = {validation_payload_name} & {{",
        "  idempotencyKey: string;",
        "};",
        f"export type {batch_payload_name} = {{",
        *(["  objectType: string;"] if action_def.target_kind == "interface" else []),
        "  targets: ActionBatchTargetInput[];",
        f"  params: {params_name};",
        "};",
        "",
    ]
    return lines


def _action_struct_type_lines(action_def: ActionDef) -> list[str]:
    lines: list[str] = []
    for parameter in action_def.parameters:
        lines.extend(_parameter_struct_type_lines(parameter))
    return lines


def _parameter_struct_type_lines(parameter: ParameterDef) -> list[str]:
    if parameter.type_name is None:
        return []
    lines: list[str] = []
    for field in parameter.fields:
        lines.extend(_parameter_struct_type_lines(field))
    lines.append(f"export type {parameter.type_name} = {{")
    for field in parameter.fields:
        suffix = "" if field.is_required else "?"
        lines.append(f"  {field.api_name}{suffix}: {field.ts_type};")
    lines.extend(["};", ""])
    return lines
