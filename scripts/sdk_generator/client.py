        "function parseFoundryLiteEventFrame<",
        "  TEvent extends FoundryLiteOperationStreamEvent,",
        ">(",
        "  frame: string,",
        "  parseEvent: StreamFoundryLiteOperationEventsOptions<TEvent>['parseEvent'],",
        "): TEvent | null {",
        "  let id: string | null = null;",
        "  let eventType: string | null = null;",
        "  let retryMs: number | null = null;",
        "  const dataLines: string[] = [];",
        "  for (const line of frame.split('\\n')) {",
        "    if (!line || line.startsWith(':')) continue;",
        "    const separator = line.indexOf(':');",
        "    const field = separator === -1 ? line : line.slice(0, separator);",
        "    let value = separator === -1 ? '' : line.slice(separator + 1);",
        "    if (value.startsWith(' ')) value = value.slice(1);",
        "    if (field === 'id') id = value;",
        "    else if (field === 'event') eventType = value;",
        "    else if (field === 'retry') retryMs = Number.isFinite(Number(value)) ? Number(value) : null;",
        "    else if (field === 'data') dataLines.push(value);",
        "  }",
        "  const raw = dataLines.join('\\n');",
        "  if (!raw && id === null && eventType === null) return null;",
        "  const metadata = { id, eventType, retryMs };",
        "  if (parseEvent) return parseEvent(raw, metadata);",
        "  return defaultFoundryLiteStreamEvent(raw, metadata) as TEvent;",
        "}",
