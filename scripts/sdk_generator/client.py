        "async function* streamObjectSubscriptionWebSocket<TItem = GenericObject>(",
        "  clientOptions: FoundryLiteClientOptions,",
        "  objectType: string,",
        "  payload: ObjectSubscriptionRequest,",
        "  options: ObjectSubscriptionOptions,",
        "): AsyncGenerator<ObjectSubscriptionStreamEvent<TItem>, void, unknown> {",
        "  const WebSocketCtor = options.webSocketImpl ?? globalThis.WebSocket;",
        "  if (!WebSocketCtor) {",
        "    throw new FoundryLiteApiError(0, 'WEBSOCKET_UNAVAILABLE', 'WebSocket is unavailable', {}, null, true);",
        "  }",
        "  const token = clientOptions.tokenProvider ? await clientOptions.tokenProvider() : clientOptions.token;",
        "  const protocols = token ? ['foundry-lite', `bearer.${token}`] : ['foundry-lite'];",
        (
            "  const socket = new WebSocketCtor("
            "objectSubscriptionWebSocketUrl(objectType, clientOptions.baseUrl), protocols);"
        ),
        "  const body = JSON.stringify(objectSubscriptionBody(payload, options));",
        "  const queueLimit = options.backpressureLimit ?? 1000;",
        "  const queue: string[] = [];",
        "  let notify: (() => void) | null = null;",
        "  let closed = false;",
        "  let failure: FoundryLiteApiError | null = null;",
        "  const wake = () => { const current = notify; notify = null; current?.(); };",
        "  socket.onopen = () => socket.send(body);",
        "  socket.onmessage = (event) => {",
        "    if (queue.length >= queueLimit) {",
        "      failure = new FoundryLiteApiError(",
        "        0,",
        "        'BACKPRESSURE_LIMIT_EXCEEDED',",
        "        'Object subscription backpressure limit exceeded',",
        "        { limit: queueLimit },",
        "        null,",
        "        false,",
        "      );",
        "      socket.close();",
        "      wake();",
        "      return;",
        "    }",
        "    queue.push(String(event.data));",
        "    wake();",
        "  };",
        (
            "  socket.onerror = () => { failure = new FoundryLiteApiError("
            "0, 'WEBSOCKET_ERROR', 'WebSocket subscription failed', {}, null, true); wake(); };"
        ),
        "  socket.onclose = () => { closed = true; wake(); };",
        "  options.signal?.addEventListener('abort', () => socket.close(), { once: true });",
        "  while (!closed || queue.length > 0) {",
        "    if (queue.length === 0) {",
        "      if (failure) throw failure;",
        "      await new Promise<void>((resolve) => { notify = resolve; });",
        "      continue;",
        "    }",
        "    const raw = String(queue.shift());",
        "    const payloadEvent = parseObjectSubscriptionPayload<TItem>(raw);",
        "    if (payloadEvent.event === 'error' && isTerminalSubscriptionError(payloadEvent.error)) {",
        "      const code = String(payloadEvent.error.code);",
        "      const status = code === 'RATE_LIMITED' ? 429 : 403;",
        "      throw new FoundryLiteApiError(",
        "        status,",
        "        code,",
        "        String(payloadEvent.error.message ?? code),",
        "        payloadEvent.error,",
        "        null,",
        "        code === 'RATE_LIMITED',",
        "      );",
        "    }",
        "    yield { id: null, eventType: payloadEvent.event, retryMs: null, payload: payloadEvent, raw };",
        "  }",
        "  if (failure) throw failure;",
        "}",
