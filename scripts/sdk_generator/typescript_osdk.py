        "  const liveLinkApiNames = hasCatalog",
        "    ? sortedOntologyApiNames(catalog.linkTypes.map((linkType) => linkType.apiName))",
        "    : [];",
        "  const dynamicOnlyObjectApiNames = hasCatalog",
        "    ? ontologyApiNameDifference(liveObjectApiNames, generatedObjectApiNames)",
