        "async function consumeObjectSubscription<TItem>(",
        "  stream: AsyncGenerator<ObjectSubscriptionStreamEvent<TItem>, void, unknown>,",
        "  callbacks: ObjectSubscriptionCallbacks<TItem>,",
        "  signal: AbortSignal,",
        "): Promise<void> {",
        "  try {",
        "    for await (const frame of stream) {",
        "      if (signal.aborted) return;",
        "      const event = frame.payload;",
        "      if (event.event === 'snapshot') callbacks.onSuccessfulSubscription?.(event);",
        "      else if (event.event === 'object_changed') callbacks.onChange?.(event);",
        "      else if (event.event === 'out_of_date') callbacks.onOutOfDate?.(event);",
        "      else if (event.event === 'error') callbacks.onError?.(event.error);",
        "    }",
        "  } catch (error) {",
        "    if (!signal.aborted) callbacks.onError?.(error);",
        "  }",
        "}",
