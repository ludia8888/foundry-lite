        "function osdkAggregateResult(",
        "  plan: OsdkAggregatePlan,",
        "  states: Map<string, OsdkAggregateState>,",
        "): OsdkAggregateResult {",
        "  if (states.size === 0 && plan.groupBy.length === 0) {",
        "    states.set('[]', { group: {}, count: 0 });",
        "  }",
        "  const buckets = Array.from(states.values());",
        "  if (plan.countOrder !== 'unordered') {",
        "    buckets.sort((left, right) =>",
        "      plan.countOrder === 'asc' ? left.count - right.count : right.count - left.count,",
        "    );",
        "  }",
        "  return {",
        "    excludedItems: 0,",
        "    data: buckets.map((state) => ({",
        "      group: state.group,",
        "      metrics: plan.metricNames.map((name) => ({ name, value: state.count })),",
        "    })),",
        "  };",
