def _api_names_csv(items: Sequence[ActionDef | InterfaceDef | LinkDef | ObjectDef]) -> str:
    return ", ".join(item.api_name for item in items)


def _api_name_values_csv(items: Sequence[ActionDef | InterfaceDef | LinkDef | ObjectDef]) -> str:
    return ", ".join(json.dumps(item.api_name) for item in items)


def _osdk_registry_lines(ontology: OntologyDef) -> list[str]:
    lines: list[str] = []
    for object_def in ontology.objects:
        lines.extend(_osdk_object_constant_lines(object_def))
    object_names = _api_names_csv(ontology.objects)
    object_name_values = _api_name_values_csv(ontology.objects)
    lines.append(f"export const $Objects = {{ {object_names} }} as const;")
    for interface_def in ontology.interfaces:
        lines.extend(_osdk_interface_constant_lines(interface_def))
    interface_names = _api_names_csv(ontology.interfaces)
    interface_name_values = _api_name_values_csv(ontology.interfaces)
    for link_def in ontology.links:
        lines.extend(_osdk_link_constant_lines(link_def))
    link_names = _api_names_csv(ontology.links)
    link_name_values = _api_name_values_csv(ontology.links)
    for action_def in ontology.actions:
        lines.extend(_osdk_action_constant_lines(action_def))
    action_names = _api_names_csv(ontology.actions)
    action_name_values = _api_name_values_csv(ontology.actions)
    lines.extend(
        [
            f"export const $Interfaces = {{ {interface_names} }} as const;",
            f"export const $Links = {{ {link_names} }} as const;",
            f"export const $Actions = {{ {action_names} }} as const;",
            "export const $Ontology = {",
            "  objects: $Objects,",
            "  interfaces: $Interfaces,",
            "  links: $Links,",
            "  actions: $Actions,",
            f"  objectApiNames: [{object_name_values}],",
            f"  interfaceApiNames: [{interface_name_values}],",
            f"  linkApiNames: [{link_name_values}],",
            f"  actionApiNames: [{action_name_values}],",
            "} as const;",
            "",
            "export function getObjectType<TName extends ObjectApiName>(apiName: TName): ObjectTypeRegistry[TName] {",
            "  const objectType = $Objects[apiName];",
            "  if (!objectType) {",
            "    throw new FoundryLiteApiError(",
            "      0,",
            '      "UNKNOWN_OSDK_OBJECT",',
            "      `Unknown OSDK object ${String(apiName)}`,",
            "      { objectApiName: String(apiName) },",
            "      null,",
            "      false,",
            "    );",
            "  }",
            "  return objectType;",
            "}",
            "",
            "export function getActionType<TName extends ActionApiName>(apiName: TName): ActionTypeRegistry[TName] {",
            "  const actionType = $Actions[apiName];",
            "  if (!actionType) {",
            "    throw new FoundryLiteApiError(",
            "      0,",
            '      "UNKNOWN_OSDK_ACTION",',
            "      `Unknown OSDK action ${String(apiName)}`,",
            "      { actionApiName: String(apiName) },",
            "      null,",
            "      false,",
            "    );",
            "  }",
            "  return actionType;",
            "}",
            "",
        ]
    )
    lines.extend(_ts_osdk_generated_relation_lines(ontology))
    lines.extend(_ts_ontology_index_lines())
    return lines


def _ts_osdk_generated_relation_lines(ontology: OntologyDef) -> list[str]:
    return [
        *_ts_link_registry_interface_lines(ontology),
        *_ts_action_registry_interface_lines(ontology),
        *_ts_osdk_link_entries_lines(ontology),
        *_ts_osdk_action_entries_lines(ontology),
    ]


def _ts_link_registry_interface_lines(ontology: OntologyDef) -> list[str]:
    lines = ["export interface OsdkGeneratedLinkRegistry {"]
    for object_def in ontology.objects:
        entries = _link_entries_for_object(ontology.links, object_def.api_name)
        if not entries:
            continue
        lines.append(f"  {object_def.api_name}: {{")
        for alias, _link_def, target_object in entries:
            lines.append(f"    {alias}: OsdkLinkSet<typeof {target_object}>;")
        lines.append("  };")
    lines.extend(["}", ""])
    return lines


def _ts_action_registry_interface_lines(ontology: OntologyDef) -> list[str]:
    lines = ["export interface OsdkGeneratedObjectActionRegistry {"]
    for object_def in ontology.objects:
        actions = [action for action in ontology.actions if action.target == object_def.api_name]
        if not actions:
            continue
        lines.append(f"  {object_def.api_name}: {{")
        for alias, action_def in _action_alias_entries(actions):
            lines.append(f"    {alias}: OsdkBoundAction<typeof {action_def.api_name}>;")
        lines.append("  };")
    lines.extend(["}", ""])
    return lines


def _ts_osdk_link_entries_lines(ontology: OntologyDef) -> list[str]:
    lines = [
        "type OsdkLinkRuntimeEntry = {",
        "  alias: string;",
        "  linkType: string;",
        "  targetObjectType: OsdkObjectType;",
        "};",
        "",
        "function osdkLinkEntries(objectType: OsdkObjectType): OsdkLinkRuntimeEntry[] {",
        "  switch (objectType.apiName) {",
    ]
    for object_def in ontology.objects:
        entries = _link_entries_for_object(ontology.links, object_def.api_name)
        lines.append(f"    case '{object_def.api_name}':")
        if entries:
            lines.append("      return [")
            for alias, link_def, target_object in entries:
                entry = f"{{ alias: '{alias}', linkType: '{link_def.api_name}', targetObjectType: {target_object} }}"
                lines.append(f"        {entry},")
            lines.append("      ];")
        else:
            lines.append("      return [];")
    lines.extend(["    default:", "      return [];", "  }", "}", ""])
    return lines


def _ts_osdk_action_entries_lines(ontology: OntologyDef) -> list[str]:
    lines = [
        "type OsdkActionRuntimeEntry = {",
        "  alias: string;",
        "  actionType: OsdkActionType;",
        "};",
        "",
        "function osdkActionEntries(objectType: OsdkObjectType): OsdkActionRuntimeEntry[] {",
        "  switch (objectType.apiName) {",
    ]
    for object_def in ontology.objects:
        actions = [action for action in ontology.actions if action.target == object_def.api_name]
        lines.append(f"    case '{object_def.api_name}':")
        if actions:
            lines.append("      return [")
            for alias, action_def in _action_alias_entries(actions):
                lines.append(f"        {{ alias: '{alias}', actionType: {action_def.api_name} }},")
            lines.append("      ];")
        else:
            lines.append("      return [];")
    lines.extend(["    default:", "      return [];", "  }", "}", ""])
    return lines


