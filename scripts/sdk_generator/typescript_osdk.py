        "  const staticOnlyObjectApiNames = hasCatalog",
        "    ? ontologyApiNameDifference(generatedObjectApiNames, liveObjectApiNames)",
        "    : [];",
        "  const dynamicOnlyActionApiNames = hasCatalog",
        "    ? ontologyApiNameDifference(liveActionApiNames, generatedActionApiNames)",
