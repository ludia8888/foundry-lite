        "  return {",
        "    manifest: SDK_PACKAGE_MANIFEST,",
        "    expectedOntologyFingerprint,",
        "    actualOntologyFingerprint,",
        "    isFingerprintMatched,",
        "    generatedObjectApiNames,",
        "    liveObjectApiNames,",
        "    dynamicOnlyObjectApiNames,",
        "    staticOnlyObjectApiNames,",
        "    generatedActionApiNames,",
        "    liveActionApiNames,",
